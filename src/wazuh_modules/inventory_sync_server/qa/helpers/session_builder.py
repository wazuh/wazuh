"""FlatBuffers FullSession builder for the QA suite.

Builds the exact wire bytes an agent (through remoted) sends: one
Message{FullSession{Start, SessionPayload}} per session. The generated Python
bindings are produced by conftest.py from the shared inventorySync.fbs (they
are never committed), so this module imports them lazily.

The builder deliberately builds WHATEVER it is told -- including combinations
the server must reject (empty values, mode-payload mismatches, non-FullSession
message types) -- because the validation matrix is half the suite.
"""

import json

import flatbuffers

# Generated by conftest.py (flatc --python); the package root is added to sys.path there.
from Wazuh.SyncSchema import (
    ChecksumModule,
    Cleans,
    DataClean,
    DataContext,
    DataValue,
    FullSession,
    Message,
    MessageType,
    Mode,
    Operation,
    Option,
    SessionPayload,
    Start,
    SyncData,
)

MODES = {
    "delta": Mode.Mode().ModuleDelta,
    "module_delta": Mode.Mode().ModuleDelta,
    "check": Mode.Mode().ModuleCheck,
    "module_check": Mode.Mode().ModuleCheck,
    "metadata_delta": Mode.Mode().MetadataDelta,
    "metadata_check": Mode.Mode().MetadataCheck,
    "group_delta": Mode.Mode().GroupDelta,
    "group_check": Mode.Mode().GroupCheck,
}

OPTIONS = {
    "sync": Option.Option().Sync,
    "vdfirst": Option.Option().VDFirst,
    "vdsync": Option.Option().VDSync,
}


def _mode(value):
    return MODES[value.lower()] if isinstance(value, str) else value


def _option(value):
    return OPTIONS[value.lower()] if isinstance(value, str) else value


def _data_bytes(data):
    """A document travels as JSON bytes; accept dicts, strings or raw bytes."""
    if isinstance(data, bytes):
        return data
    if isinstance(data, str):
        return data.encode()
    return json.dumps(data).encode()


def _build_start(builder, start):
    """Start table from a dict; only what the dict names is set (plus defaults)."""
    strings = {}
    for key in ("module", "architecture", "hostname", "osname", "osplatform", "ostype",
                "osversion", "agentversion", "agentname", "agentid", "cluster_name"):
        if start.get(key) is not None:
            strings[key] = builder.CreateString(str(start[key]))

    indices = None
    if start.get("indices") is not None:
        offsets = [builder.CreateString(index) for index in start["indices"]]
        Start.StartStartIndexVector(builder, len(offsets))
        for offset in reversed(offsets):
            builder.PrependUOffsetTRelative(offset)
        indices = builder.EndVector()

    groups = None
    if start.get("groups") is not None:
        offsets = [builder.CreateString(group) for group in start["groups"]]
        Start.StartStartGroupsVector(builder, len(offsets))
        for offset in reversed(offsets):
            builder.PrependUOffsetTRelative(offset)
        groups = builder.EndVector()

    Start.StartStart(builder)
    if "module" in strings:
        Start.StartAddModule(builder, strings["module"])
    if start.get("mode") is not None:
        Start.StartAddMode(builder, _mode(start["mode"]))
    if indices is not None:
        Start.StartAddIndex(builder, indices)
    if start.get("option") is not None:
        Start.StartAddOption(builder, _option(start["option"]))
    for key, add in (("architecture", Start.StartAddArchitecture), ("hostname", Start.StartAddHostname),
                     ("osname", Start.StartAddOsname), ("osplatform", Start.StartAddOsplatform),
                     ("ostype", Start.StartAddOstype), ("osversion", Start.StartAddOsversion),
                     ("agentversion", Start.StartAddAgentversion), ("agentname", Start.StartAddAgentname),
                     ("agentid", Start.StartAddAgentid), ("cluster_name", Start.StartAddClusterName)):
        if key in strings:
            add(builder, strings[key])
    if groups is not None:
        Start.StartAddGroups(builder, groups)
    if start.get("global_version") is not None:
        Start.StartAddGlobalVersion(builder, int(start["global_version"]))
    if start.get("feed_offset") is not None:
        Start.StartAddFeedOffset(builder, int(start["feed_offset"]))
    return Start.StartEnd(builder)


def _build_sync_data(builder, sync_data):
    value_offsets = []
    for value in sync_data.get("values", []):
        id_offset = builder.CreateString(value.get("id", ""))
        index_offset = builder.CreateString(value.get("index", ""))
        data = builder.CreateByteVector(_data_bytes(value.get("data", {})))
        DataValue.DataValueStart(builder)
        operation = value.get("operation", "upsert")
        if isinstance(operation, str):
            operation = (Operation.Operation().Delete if operation == "delete"
                         else Operation.Operation().Upsert)
        DataValue.DataValueAddOperation(builder, operation)
        DataValue.DataValueAddId(builder, id_offset)
        DataValue.DataValueAddIndex(builder, index_offset)
        if value.get("version"):
            DataValue.DataValueAddVersion(builder, int(value["version"]))
        DataValue.DataValueAddData(builder, data)
        value_offsets.append(DataValue.DataValueEnd(builder))

    context_offsets = []
    for context in sync_data.get("contexts", []):
        id_offset = builder.CreateString(context.get("id", ""))
        index_offset = builder.CreateString(context.get("index", ""))
        data = builder.CreateByteVector(_data_bytes(context.get("data", {})))
        DataContext.DataContextStart(builder)
        DataContext.DataContextAddId(builder, id_offset)
        DataContext.DataContextAddIndex(builder, index_offset)
        DataContext.DataContextAddData(builder, data)
        context_offsets.append(DataContext.DataContextEnd(builder))

    values_vector = None
    if value_offsets or "values" in sync_data:
        SyncData.SyncDataStartValuesVector(builder, len(value_offsets))
        for offset in reversed(value_offsets):
            builder.PrependUOffsetTRelative(offset)
        values_vector = builder.EndVector()

    contexts_vector = None
    if context_offsets:
        SyncData.SyncDataStartContextsVector(builder, len(context_offsets))
        for offset in reversed(context_offsets):
            builder.PrependUOffsetTRelative(offset)
        contexts_vector = builder.EndVector()

    SyncData.SyncDataStart(builder)
    if values_vector is not None:
        SyncData.SyncDataAddValues(builder, values_vector)
    if contexts_vector is not None:
        SyncData.SyncDataAddContexts(builder, contexts_vector)
    return SyncData.SyncDataEnd(builder)


def _build_cleans(builder, indices):
    item_offsets = []
    for index in indices:
        index_offset = builder.CreateString(index)
        DataClean.DataCleanStart(builder)
        DataClean.DataCleanAddIndex(builder, index_offset)
        item_offsets.append(DataClean.DataCleanEnd(builder))

    Cleans.CleansStartItemsVector(builder, len(item_offsets))
    for offset in reversed(item_offsets):
        builder.PrependUOffsetTRelative(offset)
    items = builder.EndVector()

    Cleans.CleansStart(builder)
    Cleans.CleansAddItems(builder, items)
    return Cleans.CleansEnd(builder)


def _build_checksum(builder, checksum):
    index_offset = builder.CreateString(checksum["index"]) if checksum.get("index") is not None else None
    value_offset = builder.CreateString(checksum["checksum"]) if checksum.get("checksum") is not None else None
    ChecksumModule.ChecksumModuleStart(builder)
    if index_offset is not None:
        ChecksumModule.ChecksumModuleAddIndex(builder, index_offset)
    if value_offset is not None:
        ChecksumModule.ChecksumModuleAddChecksum(builder, value_offset)
    return ChecksumModule.ChecksumModuleEnd(builder)


def build_session(start, payload=None):
    """One whole session: Message{FullSession{Start, payload}} as bytes.

    payload: {"sync_data": {...}} | {"cleans": [indices]} | {"checksum": {...}} | None.
    """
    builder = flatbuffers.Builder(1024)

    payload_type = SessionPayload.SessionPayload().NONE
    payload_offset = None
    if payload:
        if "sync_data" in payload:
            payload_type = SessionPayload.SessionPayload().SyncData
            payload_offset = _build_sync_data(builder, payload["sync_data"])
        elif "cleans" in payload:
            payload_type = SessionPayload.SessionPayload().Cleans
            payload_offset = _build_cleans(builder, payload["cleans"])
        elif "checksum" in payload:
            payload_type = SessionPayload.SessionPayload().ChecksumModule
            payload_offset = _build_checksum(builder, payload["checksum"])
        else:
            raise ValueError(f"unknown payload: {payload}")

    start_offset = _build_start(builder, start)

    FullSession.FullSessionStart(builder)
    FullSession.FullSessionAddStart(builder, start_offset)
    if payload_offset is not None:
        FullSession.FullSessionAddPayloadType(builder, payload_type)
        FullSession.FullSessionAddPayload(builder, payload_offset)
    session_offset = FullSession.FullSessionEnd(builder)

    Message.MessageStart(builder)
    Message.MessageAddContentType(builder, MessageType.MessageType().FullSession)
    Message.MessageAddContent(builder, session_offset)
    builder.Finish(Message.MessageEnd(builder))
    return bytes(builder.Output())


def build_non_full_session_message(agent_id="001", cluster_name="cluster01"):
    """A well-formed Message whose content is a bare Start -- one of the legacy
    union members the server must answer 400 (only FullSession is a session)."""
    builder = flatbuffers.Builder(256)
    start_offset = _build_start(builder, {"agentid": agent_id, "cluster_name": cluster_name})
    Message.MessageStart(builder)
    Message.MessageAddContentType(builder, MessageType.MessageType().Start)
    Message.MessageAddContent(builder, start_offset)
    builder.Finish(Message.MessageEnd(builder))
    return bytes(builder.Output())


