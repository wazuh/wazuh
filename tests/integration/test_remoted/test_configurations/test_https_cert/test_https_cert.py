# Set pytest marks.
pytestmark = [pytest.mark.server, pytest.mark.tier(level=1)]

# Cases metadata and its ids.
cases_path = Path(TEST_CASES_PATH, 'cases_https_cert.yaml')
config_path = Path(CONFIGS_PATH, 'config_https_cert.yaml')
test_configuration, test_metadata, cases_ids = get_test_cases_data(cases_path)
test_configuration = load_configuration_template(config_path, test_configuration, test_metadata)

daemons_handler_configuration = {'all_daemons': True}

local_internal_options = {REMOTED_DEBUG: '2'}

# The CA provisioned next to the listener certificate. The manager never generates certificates: in CI
# the "Provision TLS certificates" workflow step issues root-ca.pem and a remoted.pem leaf signed by it
# with wazuh-certs-tool; in the devcontainer, e2e/init.sh --certs-only + e2e/wazuh_copy_certs.sh do.
MANAGER_CA_PATH = os.path.join(WAZUH_PATH, 'etc', 'certs', 'root-ca.pem')
LISTENER_HOST = '127.0.0.1'
LISTENER_NAME = 'wazuh-manager'
LISTENER_WAIT_TIMEOUT = 30


def wait_for_listener(port: int, timeout: int = LISTENER_WAIT_TIMEOUT) -> None:
    """Block until something accepts TCP connections on the HTTPS listener port."""
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            with socket.create_connection((LISTENER_HOST, port), timeout=2):
                return
        except OSError:
            time.sleep(1)
    pytest.fail(f'Nothing is listening on {LISTENER_HOST}:{port} after {timeout} s')


def tls_handshake(port: int, cafile: str) -> bytes:
    """Complete a TLS handshake against the listener trusting only `cafile`; return the peer certificate (DER).

    Hostname checking is disabled on purpose: the chain is what is under test, the SAN is asserted
    separately from the parsed certificate.
    """
    context = ssl.create_default_context(cafile=cafile)
    context.check_hostname = False
    with socket.create_connection((LISTENER_HOST, port), timeout=10) as sock:
        with context.wrap_socket(sock, server_hostname=LISTENER_NAME, do_handshake_on_connect=False) as tls:
            tls.do_handshake()
            return tls.getpeercert(binary_form=True)


def make_foreign_ca(directory: Path) -> Path:
    """Write an ephemeral, unrelated CA certificate under `directory` and return its path."""
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, 'Foreign Test CA')])
    now = datetime.datetime.now(datetime.timezone.utc)
    cert = (x509.CertificateBuilder()
            .subject_name(name)
            .issuer_name(name)
            .public_key(key.public_key())
            .serial_number(x509.random_serial_number())
            .not_valid_before(now - datetime.timedelta(days=1))
            .not_valid_after(now + datetime.timedelta(days=1))
            .add_extension(x509.BasicConstraints(ca=True, path_length=None), critical=True)
            .sign(key, hashes.SHA256()))
    path = Path(directory, 'foreign-ca.pem')
    path.write_bytes(cert.public_bytes(serialization.Encoding.PEM))
    return path


# Test function.
@pytest.mark.parametrize('test_configuration, test_metadata', zip(test_configuration, test_metadata), ids=cases_ids)
def test_https_cert_chain(test_configuration, test_metadata, configure_local_internal_options, truncate_monitored_files,
                          set_wazuh_configuration, daemons_handler):
    '''
    description: Check that the HTTPS agent server presents the certificate provisioned for it (by the CI
                 step or the operator, never generated by the manager): a leaf signed by the manager CA
                 (etc/certs/root-ca.pem). For this purpose, it completes a
                 TLS handshake against the listener trusting only that CA, then parses the certificate the
                 server presented and checks it is a server leaf (not a CA), carries the serverAuth EKU and
                 the 'wazuh-manager' SAN, and was issued by the manager CA.

    parameters:
        - test_configuration
            type: dict
            brief: Configuration applied to wazuh-manager.conf.
        - test_metadata:
            type: dict
            brief: Test case metadata.
        - configure_local_internal_options:
            type: fixture
            brief: Configure the Wazuh local internal options using the values from `local_internal_options`.
        - truncate_monitored_files:
            type: fixture
            brief: Truncate all the log files and json alerts files before and after the test execution.
        - set_wazuh_configuration:
            type: fixture
            brief: Apply changes to the wazuh-manager.conf configuration.
        - daemons_handler:
            type: fixture
            brief: Starts/Restarts the daemons indicated in `daemons_handler_configuration` before each test,
                   once the test finishes, stops the daemons.
    '''
    port = int(test_metadata.get('port', DEFAULT_HTTPS_REMOTE_CONNECTION_PORT))
    wait_for_listener(port)

    manager_ca = x509.load_pem_x509_certificate(Path(MANAGER_CA_PATH).read_bytes())

    leaf = x509.load_der_x509_certificate(tls_handshake(port, MANAGER_CA_PATH))

    basic_constraints = leaf.extensions.get_extension_for_class(x509.BasicConstraints).value
    assert basic_constraints.ca is False, f'The listener presents a CA certificate: {leaf.subject.rfc4514_string()}'

    extended_key_usage = leaf.extensions.get_extension_for_class(x509.ExtendedKeyUsage).value
    assert ExtendedKeyUsageOID.SERVER_AUTH in extended_key_usage, 'The listener certificate lacks the serverAuth EKU'

    subject_alt_name = leaf.extensions.get_extension_for_class(x509.SubjectAlternativeName).value
    assert x509.DNSName(LISTENER_NAME) in subject_alt_name, \
        f"SAN {subject_alt_name.get_values_for_type(x509.DNSName)} lacks '{LISTENER_NAME}'"

    assert leaf.issuer == manager_ca.subject, \
        f'Issuer {leaf.issuer.rfc4514_string()} is not the manager CA {manager_ca.subject.rfc4514_string()}'


@pytest.mark.parametrize('test_configuration, test_metadata', zip(test_configuration, test_metadata), ids=cases_ids)
def test_https_cert_foreign_ca_rejected(test_configuration, test_metadata, configure_local_internal_options,
                                        truncate_monitored_files, set_wazuh_configuration, daemons_handler, tmp_path):
    '''
    description: Check that the certificate the HTTPS agent server presents is rejected when the client trusts
                 an unrelated CA. For this purpose, it generates an ephemeral CA, trusts only that CA and
                 checks the TLS handshake against the listener fails with a certificate verification error,
                 proving the positive test above distinguishes the manager CA from any other.

    parameters:
        - test_configuration
            type: dict
            brief: Configuration applied to wazuh-manager.conf.
        - test_metadata:
            type: dict
            brief: Test case metadata.
        - configure_local_internal_options:
            type: fixture
            brief: Configure the Wazuh local internal options using the values from `local_internal_options`.
        - truncate_monitored_files:
            type: fixture
            brief: Truncate all the log files and json alerts files before and after the test execution.
        - set_wazuh_configuration:
            type: fixture
            brief: Apply changes to the wazuh-manager.conf configuration.
        - daemons_handler:
            type: fixture
            brief: Starts/Restarts the daemons indicated in `daemons_handler_configuration` before each test,
                   once the test finishes, stops the daemons.
        - tmp_path:
            type: fixture
            brief: Per-test temporary directory where the ephemeral CA is written.
    '''
    port = int(test_metadata.get('port', DEFAULT_HTTPS_REMOTE_CONNECTION_PORT))
    wait_for_listener(port)

    foreign_ca = make_foreign_ca(tmp_path)

    with pytest.raises(ssl.SSLCertVerificationError):
        tls_handshake(port, str(foreign_ca))
