"""Generate docs/ref/configuration/manager/reference.md from the manager configuration schema.

The schema (src/shared_modules/manager_config/schema/wazuh-manager.schema.json) is the single source of
truth of etc/wazuh-manager.conf: types, ranges, defaults and the description of every option. This tool
renders it as one Markdown table per top-level section so the reference never drifts from the code.

    gen-manager-conf-ref.py            rewrite the reference
    gen-manager-conf-ref.py --check    exit 1 if the committed reference is out of date (docs/build.sh)
"""

import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SCHEMA = os.path.join(REPO, 'src', 'shared_modules', 'manager_config', 'schema', 'wazuh-manager.schema.json')
OUTPUT = os.path.join(REPO, 'docs', 'ref', 'configuration', 'manager', 'reference.md')

HEADER = """<!-- Generated by docs/tools/gen-manager-conf-ref.py from
     src/shared_modules/manager_config/schema/wazuh-manager.schema.json. Do not edit by hand:
     change the schema and run the tool (docs/build.sh checks that this file is up to date). -->
# Manager configuration reference

`/var/wazuh-manager/etc/wazuh-manager.conf` is a strict XML document whose root <wazuh_config> holds one element per section below. Every
option has a default: an absent option takes it, and `bin/wazuh-manager-conf dump` prints the effective
document. The file is validated against `etc/wazuh-manager.schema.json` (this reference is generated from
that schema) when the manager starts and by `bin/wazuh-manager-conf validate`; an invalid value is
reported with the JSON pointer of the offending option (`(1244): Invalid configuration at
'/remote/legacy/port': ...`). Unknown options are rejected in every section.

Paths are relative to the manager home unless absolute. Durations accept seconds as an integer or a string
with a unit suffix (`s`, `m`, `h`, `d`, `w`); sizes accept bytes or a `B`/`K`/`M`/`G` suffix.

"""


def load_schema():
    with open(SCHEMA, encoding='utf-8') as handle:
        return json.load(handle)


def resolve(node, schema):
    """Merge the definitions a node points to ($ref, allOf) into one flat dict."""
    merged = {}
    refs = []
    if '$ref' in node:
        refs.append(node['$ref'])
    for part in node.get('allOf', []):
        if '$ref' in part:
            refs.append(part['$ref'])
        else:
            merged.update(part)
    for ref in refs:
        target = schema
        for piece in ref.lstrip('#/').split('/'):
            target = target[piece]
        merged.update(resolve(target, schema))
    for key, value in node.items():
        if key not in ('$ref', 'allOf'):
            merged[key] = value
    return merged


def type_of(node):
    kind = node.get('type')
    if isinstance(kind, list):
        return ' or '.join(kind)
    if kind == 'array':
        items = resolve_items(node)
        inner = 'enum' if 'enum' in items else items.get('type', 'string')
        return f'list of {inner}'
    if kind == 'object':
        return 'mapping'
    if kind is None and 'enum' in node:
        return 'enum'
    return kind or ''


def resolve_items(node):
    return node.get('items', {})


def constraints(node, required):
    parts = []
    if 'enum' in node:
        parts.append('one of ' + ', '.join(f'`{value}`' for value in node['enum']))
    items = resolve_items(node)
    if 'enum' in items:
        parts.append('items one of ' + ', '.join(f'`{value}`' for value in items['enum']))
    if 'minimum' in node and 'maximum' in node:
        parts.append(f'{node["minimum"]}-{node["maximum"]}')
    elif 'minimum' in node:
        parts.append(f'>= {node["minimum"]}')
    elif 'maximum' in node:
        parts.append(f'<= {node["maximum"]}')
    if 'minLength' in node:
        parts.append('not empty' if node['minLength'] == 1 else f'at least {node["minLength"]} characters')
    if 'minItems' in node:
        parts.append(f'at least {node["minItems"]} item' + ('s' if node['minItems'] != 1 else ''))
    if 'maxItems' in node:
        parts.append(f'at most {node["maxItems"]} items')
    if node.get('uniqueItems'):
        parts.append('unique')
    if 'pattern' in node:
        parts.append('`' + node['pattern'].replace('|', '\\|') + '`')
    if required:
        parts.append('**required**')
    return '; '.join(parts)


def default_of(node):
    if 'default' not in node:
        return ''
    value = node['default']
    if isinstance(value, bool):
        return f'`{str(value).lower()}`'
    if isinstance(value, (list, dict)):
        return '`' + json.dumps(value) + '`'
    if value == '':
        return '`""`'
    return f'`{value}`'


def cell(text):
    return str(text).replace('|', '\\|').replace('\n', ' ')


def rows_for(node, schema, prefix, required_keys):
    """One row per property, mappings first as a heading row and then their children."""
    rows = []
    for name, raw in (node.get('properties') or {}).items():
        prop = resolve(raw, schema)
        path = f'{prefix}{name}'
        required = name in required_keys
        rows.append((path, type_of(prop), default_of(prop), constraints(prop, required), prop.get('description', '')))
        if prop.get('type') == 'object' and prop.get('properties'):
            rows.extend(rows_for(prop, schema, f'{path}.', prop.get('required', [])))
    return rows


def render(schema):
    out = [HEADER]
    out.append('## Sections\n')
    for name, raw in schema['properties'].items():
        out.append(f'- [`{name}`](#{name.replace("-", "")})')
    out.append('')
    for name, raw in schema['properties'].items():
        section = resolve(raw, schema)
        out.append(f'## `{name}`\n')
        if section.get('description'):
            out.append(section['description'] + '\n')
        out.append('| Option | Type | Default | Constraints | Description |')
        out.append('|---|---|---|---|---|')
        for path, kind, default, cons, desc in rows_for(section, schema, '', section.get('required', [])):
            out.append(f'| `{path}` | {kind} | {default} | {cell(cons)} | {cell(desc)} |')
        out.append('')
    return '\n'.join(out).rstrip('\n') + '\n'


def main(argv):
    text = render(load_schema())
    if '--check' in argv:
        try:
            with open(OUTPUT, encoding='utf-8') as handle:
                current = handle.read()
        except FileNotFoundError:
            current = None
        if current != text:
            print(f'{os.path.relpath(OUTPUT, REPO)} is out of date: run docs/tools/gen-manager-conf-ref.py', file=sys.stderr)
            return 1
        return 0
    with open(OUTPUT, 'w', encoding='utf-8') as handle:
        handle.write(text)
    print(f'wrote {os.path.relpath(OUTPUT, REPO)}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
